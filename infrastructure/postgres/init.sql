\connect booking_db


CREATE TABLE booking (
    booking_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id                INTEGER NOT NULL,

    pickup_latitude            DECIMAL(10,6) NOT NULL,
    pickup_longitude           DECIMAL(10,6) NOT NULL,
    pickup_address             VARCHAR(255),

    destination_latitude       DECIMAL(10,6) NOT NULL,
    destination_longitude      DECIMAL(10,6) NOT NULL,
    destination_address        VARCHAR(255),

    requested_vehicle_type_id  INTEGER NOT NULL,

    status                     VARCHAR(20) NOT NULL,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_booking_pickup_latitude
        CHECK (
            pickup_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_booking_pickup_longitude
        CHECK (
            pickup_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT ck_booking_destination_latitude
        CHECK (
            destination_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_booking_destination_longitude
        CHECK (
            destination_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT ck_booking_status
        CHECK (
            status IN (
                'CREATED',
                'SEARCHING',
                'ASSIGNED',
                'NO_DRIVER_FOUND'
            )
        )
);


CREATE TABLE driver_offer (
    offer_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     INTEGER NOT NULL,

    driver_id      INTEGER NOT NULL,
    vehicle_id     INTEGER NOT NULL,

    status         VARCHAR(20) NOT NULL,

    expires_at     TIMESTAMPTZ NOT NULL,
    responded_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_driver_offer_booking
        FOREIGN KEY (booking_id)
        REFERENCES booking(booking_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_driver_offer_status
        CHECK (
            status IN (
                'PENDING',
                'ACCEPTED',
                'REJECTED',
                'EXPIRED'
            )
        ),

    CONSTRAINT ck_driver_offer_response
        CHECK (
            (
                status = 'PENDING'
                AND responded_at IS NULL
            )
            OR
            (
                status IN (
                    'ACCEPTED',
                    'REJECTED',
                    'EXPIRED'
                )
            )
        )
);


CREATE TABLE driver_assignment (
    assignment_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id     INTEGER NOT NULL UNIQUE,
    offer_id       INTEGER NOT NULL UNIQUE,

    driver_id      INTEGER NOT NULL,
    vehicle_id     INTEGER NOT NULL,

    assigned_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_driver_assignment_booking
        FOREIGN KEY (booking_id)
        REFERENCES booking(booking_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_driver_assignment_offer
        FOREIGN KEY (offer_id)
        REFERENCES driver_offer(offer_id)
);


CREATE INDEX idx_booking_customer_created
    ON booking(
        customer_id,
        created_at DESC
    );


CREATE INDEX idx_booking_status
    ON booking(status);


CREATE INDEX idx_driver_offer_booking_status
    ON driver_offer(
        booking_id,
        status
    );


CREATE INDEX idx_driver_offer_driver_status
    ON driver_offer(
        driver_id,
        status
    );



-- =========================================================
-- Trip Management
-- trip-service -> trip_db
--
-- booking/customer/driver/vehicle/vehicle_type/user IDs
-- are cross-context logical references.
-- =========================================================

\connect trip_db


CREATE TABLE trip (
    trip_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id            INTEGER NOT NULL UNIQUE,
    customer_id           INTEGER NOT NULL,
    driver_id             INTEGER NOT NULL,
    vehicle_id            INTEGER NOT NULL,
    vehicle_type_id       INTEGER NOT NULL,

    distance_km           DECIMAL(10,2),

    status                VARCHAR(20) NOT NULL,

    estimated_arrival_at  TIMESTAMPTZ,

    assigned_at           TIMESTAMPTZ,
    arrived_at            TIMESTAMPTZ,
    picked_up_at          TIMESTAMPTZ,
    started_at            TIMESTAMPTZ,

    completed_at          TIMESTAMPTZ,

    canceled_at           TIMESTAMPTZ,
    cancel_reason         VARCHAR(255),
    canceled_by_user_id   INTEGER,

    CONSTRAINT ck_trip_distance
        CHECK (
            distance_km IS NULL
            OR distance_km >= 0
        ),

    CONSTRAINT ck_trip_status
        CHECK (
            status IN (
                'ASSIGNED',
                'ARRIVED',
                'PICKED_UP',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELED'
            )
        ),

    CONSTRAINT ck_trip_terminal_data
        CHECK (
            (
                status = 'COMPLETED'
                AND completed_at IS NOT NULL
                AND distance_km IS NOT NULL
            )
            OR
            (
                status = 'CANCELED'
                AND canceled_at IS NOT NULL
                AND cancel_reason IS NOT NULL
            )
            OR
            (
                status NOT IN (
                    'COMPLETED',
                    'CANCELED'
                )
            )
        )
);


CREATE TABLE trip_status_history (
    history_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id             INTEGER NOT NULL,

    from_status         VARCHAR(20),
    to_status           VARCHAR(20) NOT NULL,

    changed_by_user_id  INTEGER,
    reason              VARCHAR(255),

    changed_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_trip_status_history_trip
        FOREIGN KEY (trip_id)
        REFERENCES trip(trip_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_trip_history_from_status
        CHECK (
            from_status IS NULL
            OR from_status IN (
                'ASSIGNED',
                'ARRIVED',
                'PICKED_UP',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELED'
            )
        ),

    CONSTRAINT ck_trip_history_to_status
        CHECK (
            to_status IN (
                'ASSIGNED',
                'ARRIVED',
                'PICKED_UP',
                'IN_PROGRESS',
                'COMPLETED',
                'CANCELED'
            )
        )
);


CREATE INDEX idx_trip_customer
    ON trip(
        customer_id,
        assigned_at DESC
    );


CREATE INDEX idx_trip_driver_status
    ON trip(
        driver_id,
        status
    );


CREATE INDEX idx_trip_status
    ON trip(status);


CREATE INDEX idx_trip_history_trip_changed
    ON trip_status_history(
        trip_id,
        changed_at
    );



-- =========================================================
-- Fare & Payment
