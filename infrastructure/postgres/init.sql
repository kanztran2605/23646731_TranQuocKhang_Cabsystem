-- =========================================================
-- Driver & Vehicle Management
-- driver-service -> driver_db
--
-- user_id and reviewed_by_user_id are logical references
-- to auth_db.
-- =========================================================

\connect driver_db


CREATE EXTENSION IF NOT EXISTS postgis;


CREATE TABLE driver (
    driver_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              INTEGER NOT NULL UNIQUE,
    approval_status      VARCHAR(20) NOT NULL,
    availability_status  VARCHAR(20) NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_driver_approval_status
        CHECK (
            approval_status IN (
                'PENDING_APPROVAL',
                'APPROVED',
                'REJECTED'
            )
        ),

    CONSTRAINT ck_driver_availability_status
        CHECK (
            availability_status IN (
                'OFFLINE',
                'AVAILABLE',
                'BUSY'
            )
        )
);


CREATE TABLE driver_profile (
    driver_id                  INTEGER PRIMARY KEY,
    full_name                  VARCHAR(100) NOT NULL,
    address                    VARCHAR(255),
    date_of_birth              DATE,
    driver_license_ciphertext  VARCHAR(255) NOT NULL,
    encryption_key_version     INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT fk_driver_profile_driver
        FOREIGN KEY (driver_id)
        REFERENCES driver(driver_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_driver_profile_key_version
        CHECK (encryption_key_version >= 1)
);


CREATE TABLE driver_location (
    driver_id    INTEGER PRIMARY KEY,
    latitude     DECIMAL(10,6) NOT NULL,
    longitude    DECIMAL(10,6) NOT NULL,
    recorded_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_driver_location_driver
        FOREIGN KEY (driver_id)
        REFERENCES driver(driver_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_driver_location_latitude
        CHECK (
            latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_driver_location_longitude
        CHECK (
            longitude BETWEEN -180 AND 180
        )
);


CREATE TABLE vehicle_type (
    vehicle_type_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(50) NOT NULL,
    description      VARCHAR(255),
    status           VARCHAR(20) NOT NULL,

    CONSTRAINT ck_vehicle_type_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


CREATE TABLE vehicle (
    vehicle_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id        INTEGER NOT NULL,
    vehicle_type_id  INTEGER NOT NULL,
    license_plate    VARCHAR(20) NOT NULL UNIQUE,
    brand            VARCHAR(50),
    model            VARCHAR(50),
    status           VARCHAR(20) NOT NULL,

    CONSTRAINT fk_vehicle_driver
        FOREIGN KEY (driver_id)
        REFERENCES driver(driver_id),

    CONSTRAINT fk_vehicle_vehicle_type
        FOREIGN KEY (vehicle_type_id)
        REFERENCES vehicle_type(vehicle_type_id),

    CONSTRAINT ck_vehicle_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE'
            )
        )
);


CREATE TABLE driver_application (
    application_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id            INTEGER NOT NULL,
    vehicle_id           INTEGER NOT NULL,
    status               VARCHAR(20) NOT NULL,
    reviewed_by_user_id  INTEGER,
    rejection_reason     VARCHAR(255),
    submitted_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at          TIMESTAMPTZ,

    CONSTRAINT fk_driver_application_driver
        FOREIGN KEY (driver_id)
        REFERENCES driver(driver_id),

    CONSTRAINT fk_driver_application_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES vehicle(vehicle_id),

    CONSTRAINT ck_driver_application_status
        CHECK (
            status IN (
                'PENDING_APPROVAL',
                'APPROVED',
                'REJECTED'
            )
        ),

    CONSTRAINT ck_driver_application_review
        CHECK (
            (
                status = 'PENDING_APPROVAL'
                AND reviewed_at IS NULL
            )
            OR
            (
                status IN (
                    'APPROVED',
                    'REJECTED'
                )
                AND reviewed_at IS NOT NULL
            )
        )
);


CREATE INDEX idx_driver_eligibility
    ON driver(
        approval_status,
        availability_status
    );


CREATE INDEX idx_vehicle_driver_status
    ON vehicle(
        driver_id,
        status
    );


CREATE INDEX idx_vehicle_type_status
    ON vehicle(
        vehicle_type_id,
        status
    );


CREATE INDEX idx_driver_application_status
    ON driver_application(
        status,
        submitted_at
    );


-- PostGIS functional spatial index.
-- No extra location column is introduced because it does
-- not exist in ERD FINAL.
CREATE INDEX idx_driver_location_geography
    ON driver_location
    USING GIST (
        (
            ST_SetSRID(
                ST_MakePoint(
                    longitude::DOUBLE PRECISION,
                    latitude::DOUBLE PRECISION
                ),
                4326
            )::geography
        )
    );



-- =========================================================
-- Booking Management
-- booking-service -> booking_db
--
-- customer_id, driver_id, vehicle_id and
-- requested_vehicle_type_id are cross-context logical refs.
