-- =========================================================
-- Reporting
-- report-service -> reporting_db
--
-- Reporting contains read-model projections only.
-- No physical FK to source contexts.
-- =========================================================

\connect reporting_db


CREATE TABLE trip_report (
    report_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    period_start      DATE NOT NULL,
    period_end        DATE NOT NULL,

    trip_count        INTEGER NOT NULL,
    completed_count   INTEGER NOT NULL,
    canceled_count    INTEGER NOT NULL,

    completion_rate   DECIMAL(5,2) NOT NULL,
    cancelation_rate  DECIMAL(5,2) NOT NULL,

    generated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_trip_report_period
        CHECK (
            period_end >= period_start
        ),

    CONSTRAINT ck_trip_report_counts
        CHECK (
            trip_count >= 0
            AND completed_count >= 0
            AND canceled_count >= 0
        ),

    CONSTRAINT ck_trip_report_rates
        CHECK (
            completion_rate BETWEEN 0 AND 1
            AND cancelation_rate BETWEEN 0 AND 1
        )
);


CREATE TABLE revenue_report (
    report_id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    period_start               DATE NOT NULL,
    period_end                 DATE NOT NULL,

    total_revenue              DECIMAL(10,2) NOT NULL,
    currency                   VARCHAR(3) NOT NULL,

    successful_payment_count   INTEGER NOT NULL,
    failed_payment_count       INTEGER NOT NULL,

    generated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_revenue_report_period
        CHECK (
            period_end >= period_start
        ),

    CONSTRAINT ck_revenue_report_values
        CHECK (
            total_revenue >= 0
            AND successful_payment_count >= 0
            AND failed_payment_count >= 0
        )
);


CREATE TABLE driver_performance (
    performance_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    driver_id         INTEGER NOT NULL,

    period_start      DATE NOT NULL,
    period_end        DATE NOT NULL,

    trip_count        INTEGER NOT NULL,
    completed_count   INTEGER NOT NULL,
    canceled_count    INTEGER NOT NULL,

    completion_rate   DECIMAL(5,2) NOT NULL,
    cancelation_rate  DECIMAL(5,2) NOT NULL,

    rating            DECIMAL(3,2) NOT NULL,

    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_driver_performance_period
        CHECK (
            period_end >= period_start
        ),

    CONSTRAINT ck_driver_performance_counts
        CHECK (
            trip_count >= 0
            AND completed_count >= 0
            AND canceled_count >= 0
        ),

    CONSTRAINT ck_driver_performance_rates
        CHECK (
            completion_rate BETWEEN 0 AND 1
            AND cancelation_rate BETWEEN 0 AND 1
