\connect payment_db


CREATE TABLE fare (
    fare_id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trip_id                  INTEGER NOT NULL UNIQUE,
    vehicle_type_id          INTEGER NOT NULL,

    amount                   DECIMAL(10,2) NOT NULL,
    currency                 VARCHAR(3) NOT NULL,

    pricing_data             JSON NOT NULL,
    pricing_policy_snapshot  JSON NOT NULL,

    calculated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_fare_amount
        CHECK (amount >= 0)
);


CREATE TABLE payment (
    payment_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fare_id             INTEGER NOT NULL UNIQUE,

    trip_id             INTEGER NOT NULL,
    customer_id         INTEGER NOT NULL,

    amount              DECIMAL(10,2) NOT NULL,
    currency            VARCHAR(3) NOT NULL,

    payment_method      VARCHAR(50) NOT NULL,
    payment_status      VARCHAR(20) NOT NULL,

    idempotency_key     VARCHAR(100) NOT NULL UNIQUE,

    provider_reference  VARCHAR(100),
    failure_reason      VARCHAR(255),

    paid_at             TIMESTAMPTZ,

    CONSTRAINT fk_payment_fare
        FOREIGN KEY (fare_id)
        REFERENCES fare(fare_id),

    CONSTRAINT ck_payment_amount
        CHECK (amount >= 0),

    CONSTRAINT ck_payment_method
        CHECK (
            payment_method IN (
                'CASH',
                'ELECTRONIC'
            )
        ),

    CONSTRAINT ck_payment_status
        CHECK (
            payment_status IN (
                'PENDING',
                'COMPLETED',
                'FAILED'
            )
        ),

    CONSTRAINT ck_payment_paid_at
        CHECK (
            (
                payment_status = 'COMPLETED'
                AND paid_at IS NOT NULL
            )
            OR
            (
                payment_status <> 'COMPLETED'
            )
        )
);


CREATE TABLE payment_transaction (
    transaction_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          INTEGER NOT NULL,

    provider_reference  VARCHAR(100),

    transaction_status  VARCHAR(20) NOT NULL,

    amount              DECIMAL(10,2) NOT NULL,
    currency            VARCHAR(3) NOT NULL,

    failure_reason      VARCHAR(255),

    processed_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payment_transaction_payment
        FOREIGN KEY (payment_id)
        REFERENCES payment(payment_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_payment_transaction_status
        CHECK (
            transaction_status IN (
                'PENDING',
                'COMPLETED',
                'FAILED'
            )
        ),

    CONSTRAINT ck_payment_transaction_amount
        CHECK (amount >= 0)
);


CREATE INDEX idx_payment_trip
    ON payment(trip_id);


CREATE INDEX idx_payment_customer_status
    ON payment(
        customer_id,
        payment_status
    );


CREATE INDEX idx_payment_transaction_payment_processed
    ON payment_transaction(
        payment_id,
        processed_at
    );



