-- CAB System PostgreSQL bootstrap.
-- Local development uses one PostgreSQL instance with
-- 10 logically isolated databases.
--
-- IMPORTANT:
-- Cross-context IDs are logical references only.
-- No physical FK may cross microservice databases.

CREATE DATABASE auth_db;
CREATE DATABASE customer_db;
CREATE DATABASE driver_db;
CREATE DATABASE booking_db;
CREATE DATABASE trip_db;
CREATE DATABASE payment_db;
CREATE DATABASE notification_db;
CREATE DATABASE review_db;
CREATE DATABASE reporting_db;
CREATE DATABASE audit_db;


-- =========================================================
-- Identity & Access
-- auth-service -> auth_db
-- =========================================================

\connect auth_db


CREATE TABLE role (
    role_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name     VARCHAR(50) NOT NULL UNIQUE,
    description   VARCHAR(255)
);


CREATE TABLE permission (
    permission_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code  VARCHAR(80) NOT NULL UNIQUE,
    description      VARCHAR(255)
);


CREATE TABLE role_permission (
    role_id        INTEGER NOT NULL,
    permission_id  INTEGER NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (role_id, permission_id),

    CONSTRAINT fk_role_permission_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_role_permission_permission
        FOREIGN KEY (permission_id)
        REFERENCES permission(permission_id)
        ON DELETE CASCADE
);


CREATE TABLE user_account (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone          VARCHAR(20) NOT NULL UNIQUE,
    email          VARCHAR(100) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role_id        INTEGER NOT NULL,
    status         VARCHAR(20) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_account_role
        FOREIGN KEY (role_id)
        REFERENCES role(role_id),

    CONSTRAINT ck_user_account_status
        CHECK (
            status IN (
                'ACTIVE',
                'DISABLED'
            )
        )
);


CREATE TABLE refresh_token (
    token_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER NOT NULL,
    token_hash    VARCHAR(255) NOT NULL UNIQUE,
    expires_at    TIMESTAMPTZ NOT NULL,
    revoked_at    TIMESTAMPTZ,
    device_info   VARCHAR(255),

    CONSTRAINT fk_refresh_token_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id)
        ON DELETE CASCADE
);


CREATE TABLE otp_verification (
    otp_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER,
    phone          VARCHAR(20) NOT NULL,
    otp_hash       VARCHAR(255) NOT NULL,
    purpose        VARCHAR(50) NOT NULL,
    expires_at     TIMESTAMPTZ NOT NULL,
    verified_at    TIMESTAMPTZ,
    attempt_count  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_otp_verification_user
        FOREIGN KEY (user_id)
        REFERENCES user_account(user_id)
        ON DELETE CASCADE,

    CONSTRAINT ck_otp_attempt_count
        CHECK (attempt_count >= 0)
);


CREATE INDEX idx_user_account_role_status
    ON user_account(role_id, status);

CREATE INDEX idx_refresh_token_user
    ON refresh_token(user_id);

CREATE INDEX idx_otp_verification_phone_purpose
    ON otp_verification(phone, purpose);



